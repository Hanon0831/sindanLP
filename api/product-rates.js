// ---------------------------------------------------------------------------
// 容量から該当するベースレンジを取り出す
// ---------------------------------------------------------------------------
export function findCapacityTier(tiers, capacity, key) {
  if (capacity == null) return null;
  return tiers.find((t) => capacity < t[key]) || tiers[tiers.length - 1];
}

// ---------------------------------------------------------------------------
// 容量帯 × 機種ポジション から、その見積もりに当てはまる相場レンジを求める
// ---------------------------------------------------------------------------
export function resolveRange(tier, model) {
  if (!tier) return null;
  const factor = POSITION_FACTOR[model?.position] ?? POSITION_FACTOR.mid;
  return {
    min: Math.round(tier.min * factor),
    max: Math.round(tier.max * factor),
    tierLabel: tier.label,
  };
}

// ---------------------------------------------------------------------------
// テキストから該当機種を探す
// ---------------------------------------------------------------------------
export function findModel(models, ...texts) {
  const haystack = texts.filter(Boolean).join(" ").toLowerCase();
  if (!haystack) return null;
  // match文字列が長いもの（=より具体的な型番）を優先して判定する
  const sorted = [...models].sort(
    (a, b) => Math.max(...b.match.map((m) => m.length)) - Math.max(...a.match.map((m) => m.length))
  );
  for (const model of sorted) {
    if (model.match.some((m) => haystack.includes(m.toLowerCase()))) return model;
  }
  return null;
}
